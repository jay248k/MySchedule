import * as XLSX from 'xlsx';

/**
 * Clean helper to download a Blob as a file
 */
function downloadBlob(blob, filename) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/**
 * 1. Export Data to Real Excel (.xlsx) file using SheetJS
 * @param {Array<Object>} rows - Array of objects containing row data
 * @param {string} filename - Output filename (e.g. 'Pending_Tasks_Report.xlsx')
 * @param {string} sheetName - Excel sheet name
 */
export function exportToExcel(rows, filename = 'Report.xlsx', sheetName = 'Report') {
  if (!rows || rows.length === 0) {
    console.warn('Export canceled: No data available to export.');
    return;
  }

  // Create worksheet from JSON
  const worksheet = XLSX.utils.json_to_sheet(rows);

  // Auto-fit column widths
  const keys = Object.keys(rows[0] || {});
  const colWidths = keys.map((key) => {
    let maxLen = key.length;
    rows.forEach((row) => {
      const val = row[key] ? String(row[key]) : '';
      if (val.length > maxLen) maxLen = val.length;
    });
    return { wch: Math.min(Math.max(maxLen + 3, 10), 40) };
  });
  worksheet['!cols'] = colWidths;

  // Create workbook
  const workbook = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(workbook, worksheet, sheetName);

  // Generate binary XLSX
  const cleanFilename = filename.endsWith('.xlsx') ? filename : `${filename}.xlsx`;
  XLSX.writeFile(workbook, cleanFilename);
}

/**
 * 2. Export Report to Formatted Microsoft Word (.doc / .docx compatible)
 * @param {Object} options - Configuration options
 * @param {string} options.title - Report title
 * @param {Array<Object>} options.summaryStats - Key stats to display at top
 * @param {Array<string>} options.columns - Column headers
 * @param {Array<Array<string>>} options.rows - Row values matching columns
 * @param {string} options.filename - File name to save
 */
export function exportToWord({
  title = 'MySchedule Report',
  summaryStats = [],
  columns = [],
  rows = [],
  filename = 'Report.doc',
}) {
  const statsHtml = summaryStats.length > 0
    ? `
      <table style="width: 100%; margin-bottom: 24px; border-collapse: collapse; font-family: Arial, sans-serif;">
        <tr>
          ${summaryStats
            .map(
              (s) => `
            <td style="padding: 12px; background: #F1F5F9; border: 1px solid #CBD5E1; text-align: center; border-radius: 6px;">
              <div style="font-size: 11px; color: #64748B; font-weight: bold; text-transform: uppercase;">${s.label}</div>
              <div style="font-size: 20px; color: #0F172A; font-weight: bold; margin-top: 4px;">${s.value}</div>
            </td>
          `
            )
            .join('')}
        </tr>
      </table>
    `
    : '';

  const tableHeaderHtml = `
    <tr style="background-color: #0F172A; color: #FFFFFF;">
      ${columns
        .map(
          (col) =>
            `<th style="padding: 10px 12px; text-align: left; font-size: 12px; font-weight: bold; border: 1px solid #334155;">${col}</th>`
        )
        .join('')}
    </tr>
  `;

  const tableRowsHtml = rows
    .map(
      (row, idx) => `
    <tr style="background-color: ${idx % 2 === 0 ? '#FFFFFF' : '#F8FAFC'};">
      ${row
        .map(
          (cell) =>
            `<td style="padding: 9px 12px; font-size: 11px; border: 1px solid #E2E8F0; color: #334155;">${cell !== undefined && cell !== null ? String(cell) : '-'}</td>`
        )
        .join('')}
    </tr>
  `
    )
    .join('');

  const wordHtml = `
    <html xmlns:o='urn:schemas-microsoft-com:office:office' xmlns:w='urn:schemas-microsoft-com:office:word' xmlns='http://www.w3.org/TR/REC-html40'>
      <head>
        <meta charset='utf-8'>
        <title>${title}</title>
        <style>
          body { font-family: 'Segoe UI', Tahoma, Geneva, Verdana, sans-serif; margin: 30px; color: #0F172A; }
          h1 { color: #0F172A; font-size: 24px; margin-bottom: 4px; }
          p.meta { color: #64748B; font-size: 12px; margin-top: 0; margin-bottom: 20px; }
          table { width: 100%; border-collapse: collapse; font-family: 'Segoe UI', Tahoma, Geneva, Verdana, sans-serif; }
        </style>
      </head>
      <body>
        <h1>${title}</h1>
        <p class="meta">Generated by MySchedule Platform on ${new Date().toLocaleDateString()} at ${new Date().toLocaleTimeString()}</p>
        ${statsHtml}
        <table>
          <thead>${tableHeaderHtml}</thead>
          <tbody>${tableRowsHtml}</tbody>
        </table>
        <p style="margin-top: 30px; font-size: 10px; color: #94A3B8; text-align: center;">MySchedule · Performance Analytics & Work Execution Hub</p>
      </body>
    </html>
  `;

  const blob = new Blob([wordHtml], { type: 'application/msword;charset=utf-8' });
  const cleanFilename = filename.endsWith('.doc') ? filename : `${filename}.doc`;
  downloadBlob(blob, cleanFilename);
}

